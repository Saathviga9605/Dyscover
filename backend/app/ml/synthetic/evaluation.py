"""Honest evaluation metrics and reporting for synthetic interaction-profile classifiers.

All outputs generated by this module are explicitly marked SYNTHETIC_RESEARCH_ONLY.
High classification performance reflects simulator recovery, NOT clinical dyslexia detection.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from typing import Any

from app.ml.evaluation import class_distribution, classification_metrics


def build_confusion_matrix(actual: list[str], predicted: list[str], classes: list[str]) -> dict[str, dict[str, int]]:
    """Compute confusion matrix mapping actual classes to predicted class counts."""
    matrix: dict[str, dict[str, int]] = {c: {c2: 0 for c2 in classes} for c in classes}
    for a, p in zip(actual, predicted):
        if a in matrix and p in matrix[a]:
            matrix[a][p] += 1
    return matrix


def evaluate_partition(
    actual: list[str],
    predicted: list[str],
    all_classes: list[str],
) -> dict[str, Any]:
    """Compute detailed classification metrics including macro-F1, per-class metrics, and confusion matrix."""
    if not actual or len(actual) != len(predicted):
        return {}

    base_metrics = classification_metrics(actual, predicted)
    conf_matrix = build_confusion_matrix(actual, predicted, all_classes)

    return {
        "accuracy": base_metrics.get("accuracy"),
        "balanced_accuracy": base_metrics.get("balanced_accuracy"),
        "macro_f1": base_metrics.get("macro_f1") or base_metrics.get("f1"),
        "per_class": base_metrics.get("per_class", {}),
        "confusion_matrix": conf_matrix,
        "sample_count": len(actual),
    }


def evaluate_subgroups(
    rows: list[dict[str, Any]],
    actual: list[str],
    predicted: list[str],
) -> dict[str, Any]:
    """Evaluate performance across subgroups: game families, language, and modality presence."""
    by_game: dict[str, tuple[list[str], list[str]]] = defaultdict(lambda: ([], []))
    by_lang: dict[str, tuple[list[str], list[str]]] = defaultdict(lambda: ([], []))
    by_gaze: dict[str, tuple[list[str], list[str]]] = defaultdict(lambda: ([], []))
    by_speech: dict[str, tuple[list[str], list[str]]] = defaultdict(lambda: ([], []))

    for row, a, p in zip(rows, actual, predicted):
        g = row.get("game_id", "unknown")
        l = row.get("language", "unknown")
        gaze_on = bool(row.get("features", {}).get("gaze_available", {}).get("value"))
        speech_on = bool(row.get("features", {}).get("speech_available", {}).get("value"))

        by_game[g][0].append(a)
        by_game[g][1].append(p)

        by_lang[l][0].append(a)
        by_lang[l][1].append(p)

        gaze_key = "gaze_available" if gaze_on else "gaze_missing"
        by_gaze[gaze_key][0].append(a)
        by_gaze[gaze_key][1].append(p)

        speech_key = "speech_available" if speech_on else "speech_missing"
        by_speech[speech_key][0].append(a)
        by_speech[speech_key][1].append(p)

    def _acc(pair: tuple[list[str], list[str]]) -> dict[str, Any]:
        acts, preds = pair
        if not acts:
            return {"accuracy": None, "count": 0}
        correct = sum(x == y for x, y in zip(acts, preds))
        return {"accuracy": correct / len(acts), "count": len(acts)}

    return {
        "by_game": {g: _acc(pair) for g, pair in by_game.items()},
        "by_language": {l: _acc(pair) for l, pair in by_lang.items()},
        "by_gaze_modality": {m: _acc(pair) for m, pair in by_gaze.items()},
        "by_speech_modality": {m: _acc(pair) for m, pair in by_speech.items()},
    }


def generate_evaluation_report(
    algorithm: str,
    train_subjects: int,
    val_subjects: int,
    test_subjects: int,
    val_metrics: dict[str, Any],
    test_metrics: dict[str, Any],
    subgroup_metrics: dict[str, Any],
    dummy_test_accuracy: float | None = None,
) -> dict[str, Any]:
    """Generate comprehensive, honest research evaluation report."""
    return {
        "status": "SYNTHETIC_RESEARCH_ONLY",
        "scientific_disclaimer": (
            "NOTICE: These metrics measure recovery of simulator-defined interaction profiles only. "
            "They do NOT demonstrate clinical dyslexia detection, diagnostic validity, or real-world generalization. "
            "Production dyslexia inference remains strictly unavailable."
        ),
        "algorithm": algorithm,
        "partitions": {
            "train_subject_count": train_subjects,
            "validation_subject_count": val_subjects,
            "test_subject_count": test_subjects,
        },
        "validation_metrics": val_metrics,
        "test_metrics": test_metrics,
        "subgroup_breakdown": subgroup_metrics,
        "baseline_comparison": {
            "dummy_test_accuracy": dummy_test_accuracy,
            "test_accuracy": test_metrics.get("accuracy"),
            "improvement_over_chance": (
                test_metrics.get("accuracy", 0.0) - dummy_test_accuracy
                if (test_metrics.get("accuracy") is not None and dummy_test_accuracy is not None)
                else None
            ),
        },
    }

